(*
  alvie plugin types: the Python constructors of a plugin's observations, for the backends written with the Python
  SDK. Each kind of observation (and each record type) becomes a function whose keyword arguments are its fields,
  checked as Core checks them (the range of an int, the constants of an enum), and which returns the value in its
  JSON form: Exit(time=3) is {"Exit": {"time": 3}}. Fields keep the order of the declaration, as Core requires.
*)
open Core
open Alvie_plugin

let python_keywords =
  [ "False"; "None"; "True"; "and"; "as"; "assert"; "async"; "await"; "break"; "class"; "continue"; "def"; "del"; "elif";
    "else"; "except"; "finally"; "for"; "from"; "global"; "if"; "import"; "in"; "is"; "lambda"; "nonlocal"; "not"; "or";
    "pass"; "raise"; "return"; "try"; "while"; "with"; "yield" ]

let ident s = if List.mem python_keywords s ~equal:String.equal then s ^ "_" else s

let generate (p : Plugin.t) : string =
  let o = p.observations in
  let b = Buffer.create 4096 in
  let add fmt = Printf.bprintf b fmt in
  add "# The observations of plugin %s %s, generated by: alvie plugin types plugins/%s %s_types.py\n" p.manifest.name p.manifest.version p.manifest.name
    (String.map p.manifest.name ~f:(fun c -> if Char.equal c '-' then '_' else c));
  add "# Do not edit: generate it again when observations.yaml changes.\n\n";
  add "from alvie_plugin import check_int, check_bool, check_enum\n\n";
  let check name (f : Observations_file.ftype) var =
    match f with
    | F_int (lo, hi) -> sprintf "check_int(%S, %s, %s, %s)" name var (if lo = Int.min_value then "None" else Int.to_string lo) (if hi = Int.max_value then "None" else Int.to_string hi)
    | F_bool -> sprintf "check_bool(%S, %s)" name var
    | F_enum e ->
      let cs = match List.Assoc.find o.types ~equal:String.equal e with Some (Enum cs) -> cs | _ -> [] in
      sprintf "check_enum(%S, %s, [%s])" name var (String.concat ~sep:", " (List.map cs ~f:(sprintf "%S")))
    | F_record r -> sprintf "_record(%S, %S, %s)" name r var in
  add "def _record(name, record, value):\n    if not (isinstance(value, dict) and list(value) == [record]):\n        raise ValueError(f\"{name}: expected a {record} (made with {record}(...)), not {value!r}\")\n    return value\n\n";
  let constructor name ~doc fields =
    let args = List.map fields ~f:(fun (f, _) -> ident f) in
    add "\ndef %s(%s):\n" (ident name) (match args with [] -> "" | _ -> "*, " ^ String.concat ~sep:", " args);
    Option.iter doc ~f:(fun d -> add "    \"\"\"%s\"\"\"\n" (String.substr_replace_all d ~pattern:"\"" ~with_:"'"));
    add "    return {%S: {%s}}\n" name
      (String.concat ~sep:", " (List.map fields ~f:(fun (f, ty) -> sprintf "%S: %s" f (check (name ^ "." ^ f) ty (ident f))))) in
  List.iter o.types ~f:(fun (name, decl) ->
      match decl with
      | Record fields -> constructor name ~doc:(Some (sprintf "A %s (a record of observations.yaml)" name)) fields
      | Enum cs -> add "\n%s = [%s]  # the constants of the enum %s\n" (String.uppercase (ident name)) (String.concat ~sep:", " (List.map cs ~f:(sprintf "%S"))) name);
  List.iter o.kinds ~f:(fun k -> constructor k.name ~doc:k.doc k.fields);
  add "\nKINDS = [%s]\n" (String.concat ~sep:", " (List.map o.kinds ~f:(fun k -> sprintf "%S" k.name)));
  Buffer.contents b
