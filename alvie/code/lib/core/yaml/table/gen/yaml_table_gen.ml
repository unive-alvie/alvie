(* yaml_table_gen FILE...: the OCaml source of a table from the MD5 of each file's text to its YAML events *)
open Alvie_yaml

let opt = function None -> "None" | Some s -> Printf.sprintf "(Some %S)" s

let event : Yaml_event.t -> string = function
  | Stream_start -> "Stream_start" | Stream_end -> "Stream_end"
  | Document_start -> "Document_start" | Document_end -> "Document_end"
  | Mapping_start { anchor; tag } -> Printf.sprintf "Mapping_start { anchor = %s; tag = %s }" (opt anchor) (opt tag)
  | Mapping_end -> "Mapping_end"
  | Sequence_start { anchor; tag } -> Printf.sprintf "Sequence_start { anchor = %s; tag = %s }" (opt anchor) (opt tag)
  | Sequence_end -> "Sequence_end"
  | Scalar { anchor; tag; value; quoted } ->
    Printf.sprintf "Scalar { anchor = %s; tag = %s; value = %S; quoted = %b }" (opt anchor) (opt tag) value quoted
  | Alias { anchor } -> Printf.sprintf "Alias { anchor = %S }" anchor

let () =
  print_string "(* Generated by lib/core/yaml/table/gen from the YAML files of plugins/ *)\nopen Yaml_event\n\nlet table = [\n";
  List.iter (fun file ->
      let text = let ic = open_in_bin file in let s = really_input_string ic (in_channel_length ic) in close_in ic; s in
      match Yaml_parser.create text with
      | Error _ -> ()
      | Ok p ->
        let rec events acc =
          match Yaml_parser.next p with
          | Error _ -> None
          | Ok ((Stream_end, _) as e) -> Some (List.rev (e :: acc))
          | Ok e -> events (e :: acc) in
        match events [] with
        | None -> () (* an invalid file: the table does not have it, so it cannot be read *)
        | Some es ->
          Printf.printf "  (%S, [|\n" (Digest.to_hex (Digest.string text));
          List.iter (fun (e, (pos : Yaml_event.pos)) -> Printf.printf "    (%s, { line = %d; col = %d });\n" (event e) pos.line pos.col) es;
          print_string "  |]);\n")
    (List.tl (Array.to_list Sys.argv));
  print_string "]\n"
