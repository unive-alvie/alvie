(*
  The correspondence between the Sancus atoms of attacker.ml and enclave.ml and their values under the grammar of
  plugins/sancus/atoms.yaml (Alvie_plugin.Value). Core parses specs into values; until the backend works on values
  (M4), these functions translate in both directions, and the tests check that the two parsers agree on spec-lib.
*)

open Core
open Common
module V = Alvie_plugin.Value

let node tag fields = V.Node (tag, fields)

let of_reg (R i) = node "reg" [ ("i", V.Int i) ]

let of_src = function
  | S_AT r -> node "at" [ ("r", of_reg r) ]
  | S_AMP s -> node "amp" [ ("s", V.Sym s) ]
  | S_IMM v -> node "imm" [ ("v", V.Sym v) ]
  | S_R r -> node "reg" [ ("r", of_reg r) ]
  | S_SECRET -> V.Hole Alvie_plugin.Grammar.secret_name

let of_dst = function
  | D_AMP r -> node "amp_reg" [ ("r", of_reg r) ]
  | D_AMP_MEM s -> node "amp_mem" [ ("s", V.Sym s) ]
  | D_R r -> node "reg" [ ("r", of_reg r) ]

(* I_JZ, I_JNZ and I_NAMED have no syntax in specs: they are generated by code generation only *)
let rec of_inst = function
  | I_NOP -> Ok (node "nop" [])
  | I_DINT -> Ok (node "dint" [])
  | I_JMP s -> Ok (node "jmp" [ ("dst", of_src s) ])
  | I_PUSH s -> Ok (node "push" [ ("src", of_src s) ])
  | I_MOV (s, d) -> Ok (node "mov" [ ("src", of_src s); ("dst", of_dst d) ])
  | I_ADD (s, d) -> Ok (node "add" [ ("src", of_src s); ("dst", of_dst d) ])
  | I_CMP (s, d) -> Ok (node "cmp" [ ("src", of_src s); ("dst", of_dst d) ])
  | (I_JZ _ | I_JNZ _ | I_NAMED _) as i -> Error (sprintf "%s has no syntax in specs" (show_instruction_t i))

and of_inst_exn i = Result.ok_or_failwith (of_inst i)

let rec of_attacker (a : Attacker.Attacker.atom_t) : V.t =
  match a with
  | CRstNZ -> node "rst_nz" []
  | CRst -> node "rst" []
  | CJmpIn s -> node "jin" [ ("s", V.Sym s) ]
  | CCreateEncl (ts, te, ds, de) -> node "create" [ ("ts", V.Sym ts); ("te", V.Sym te); ("ds", V.Sym ds); ("de", V.Sym de) ]
  | CTimerEnable t -> node "timer_enable" [ ("t", V.Int t) ]
  | CStartCounting t -> node "start_counting" [ ("t", V.Int t) ]
  | CReti -> node "reti" []
  | CInst i -> node "inst" [ ("i", of_inst_exn i) ]
  | CIfZ (l, r) -> node "ifz" [ ("then", V.List (List.map l ~f:of_attacker)); ("else", V.List (List.map r ~f:of_attacker)) ]

let rec of_enclave (a : Enclave.Enclave.atom_t) : V.t =
  match a with
  | CRst -> node "rst" []
  | CInst i -> node "inst" [ ("i", of_inst_exn i) ]
  | CUbr -> node "ubr" []
  | CBalancedIfZ is -> node "balanced_ifz" [ ("body", V.List (List.map is ~f:of_inst_exn)) ]
  | CIfZ (l, r) -> node "ifz" [ ("then", V.List (List.map l ~f:of_enclave)); ("else", V.List (List.map r ~f:of_enclave)) ]

(* From values *)

let fail v = Error (sprintf "not a Sancus value: %s" (V.to_string v))

let to_reg = function V.Node ("reg", [ ("i", V.Int i) ]) -> Ok (R i) | v -> fail v

let to_src v =
  let open Result.Let_syntax in
  match v with
  | V.Node ("at", [ ("r", r) ]) -> let%map r = to_reg r in S_AT r
  | V.Node ("amp", [ ("s", V.Sym s) ]) -> Ok (S_AMP s)
  | V.Node ("imm", [ ("v", V.Sym s) ]) -> Ok (S_IMM s)
  | V.Node ("reg", [ ("r", r) ]) -> let%map r = to_reg r in S_R r
  | V.Hole _ -> Ok S_SECRET
  | v -> fail v

let to_dst v =
  let open Result.Let_syntax in
  match v with
  | V.Node ("amp_reg", [ ("r", r) ]) -> let%map r = to_reg r in D_AMP r
  | V.Node ("amp_mem", [ ("s", V.Sym s) ]) -> Ok (D_AMP_MEM s)
  | V.Node ("reg", [ ("r", r) ]) -> let%map r = to_reg r in D_R r
  | v -> fail v

let to_inst v =
  let open Result.Let_syntax in
  match v with
  | V.Node ("nop", []) -> Ok I_NOP
  | V.Node ("dint", []) -> Ok I_DINT
  | V.Node ("jmp", [ ("dst", s) ]) -> let%map s = to_src s in I_JMP s
  | V.Node ("push", [ ("src", s) ]) -> let%map s = to_src s in I_PUSH s
  | V.Node ("mov", [ ("src", s); ("dst", d) ]) -> let%bind s = to_src s in let%map d = to_dst d in I_MOV (s, d)
  | V.Node ("add", [ ("src", s); ("dst", d) ]) -> let%bind s = to_src s in let%map d = to_dst d in I_ADD (s, d)
  | V.Node ("cmp", [ ("src", s); ("dst", d) ]) -> let%bind s = to_src s in let%map d = to_dst d in I_CMP (s, d)
  | v -> fail v

let all_map vs ~f = Result.all (List.map vs ~f)

let rec to_attacker v : (Attacker.Attacker.atom_t, string) Result.t =
  let open Result.Let_syntax in
  match v with
  | V.Node ("rst_nz", []) -> Ok Attacker.Attacker.CRstNZ
  | V.Node ("rst", []) -> Ok CRst
  | V.Node ("jin", [ ("s", V.Sym s) ]) -> Ok (CJmpIn s)
  | V.Node ("create", [ ("ts", V.Sym ts); ("te", V.Sym te); ("ds", V.Sym ds); ("de", V.Sym de) ]) -> Ok (CCreateEncl (ts, te, ds, de))
  | V.Node ("timer_enable", [ ("t", V.Int t) ]) -> Ok (CTimerEnable t)
  | V.Node ("start_counting", [ ("t", V.Int t) ]) -> Ok (CStartCounting t)
  | V.Node ("reti", []) -> Ok CReti
  | V.Node ("inst", [ ("i", i) ]) -> let%map i = to_inst i in Attacker.Attacker.CInst i
  | V.Node ("ifz", [ ("then", V.List l); ("else", V.List r) ]) ->
    let%bind l = all_map l ~f:to_attacker in
    let%map r = all_map r ~f:to_attacker in
    Attacker.Attacker.CIfZ (l, r)
  | v -> fail v

let rec to_enclave v : (Enclave.Enclave.atom_t, string) Result.t =
  let open Result.Let_syntax in
  match v with
  | V.Node ("rst", []) -> Ok Enclave.Enclave.CRst
  | V.Node ("inst", [ ("i", i) ]) -> let%map i = to_inst i in Enclave.Enclave.CInst i
  | V.Node ("ubr", []) -> Ok CUbr
  | V.Node ("balanced_ifz", [ ("body", V.List is) ]) -> let%map is = all_map is ~f:to_inst in Enclave.Enclave.CBalancedIfZ is
  | V.Node ("ifz", [ ("then", V.List l); ("else", V.List r) ]) ->
    let%bind l = all_map l ~f:to_enclave in
    let%map r = all_map r ~f:to_enclave in
    Enclave.Enclave.CIfZ (l, r)
  | v -> fail v

(* Bodies *)

module S = Alvie_plugin.Spec

let rec of_attacker_body (b : Attacker.Attacker.body_t) : S.body =
  match b with
  | Empty -> S.Empty
  | Epsilon -> S.Epsilon
  | Atom a -> S.Atom (of_attacker a)
  | Choice (l, r) -> S.Choice (of_attacker_body l, of_attacker_body r)
  | Seq (l, r) -> S.Seq (of_attacker_body l, of_attacker_body r)
  | Star b -> S.Star (of_attacker_body b)

let rec of_enclave_body (b : Enclave.Enclave.body_t) : S.body =
  match b with
  | Empty -> S.Empty
  | Epsilon -> S.Epsilon
  | Atom a -> S.Atom (of_enclave a)
  | Choice (l, r) -> S.Choice (of_enclave_body l, of_enclave_body r)
  | Seq (l, r) -> S.Seq (of_enclave_body l, of_enclave_body r)
  | Star b -> S.Star (of_enclave_body b)

(* A spec of testdl.ml as the sections of plugins/sancus/sections.yaml, in their order *)
let of_test_spec ((Enclave e, ISR i, Prepare p, Cleanup c) : Testdl.test_spec_t) : (string * S.body) list =
  [ ("enclave", of_enclave_body e); ("isr", of_attacker_body i); ("prepare", of_attacker_body p); ("cleanup", of_attacker_body c) ]
